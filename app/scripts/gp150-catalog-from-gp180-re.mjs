#!/usr/bin/env node
// Builds src/renderer/src/gp150/lib/catalog-data.mjs, the GP-150 effect catalog Tone Studio ships, from
// majabojarska/Valeton-GP180-Rev-Eng (GPL-3.0) at a pinned commit: effect-wire-schema.json, its normalized form of
// Valeton Suite 2.1.0's module150_data.json (the effect list of the GP-150 / GP-180 generation).
//
// Per model: module (storage order PRE WAH DST NS AMP NR CAB EQ MOD DLY RVB VOL), model id, name, and its params by
// param id: range, step, default, kind (widgetType 0 knob, 1 switch, 2 menu, 3 centred knob), menu labels, and the id
// of the Sync switch that turns a Time/Rate knob into note values.
//
// Usage: node scripts/gp150-catalog-from-gp180-re.mjs   (needs network; writes the file, prints the counts)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "majabojarska/Valeton-GP180-Rev-Eng";
const COMMIT = "11edfe521f7d43bf9489855fdedec7dab1de8462";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "renderer", "src", "gp150", "lib", "catalog-data.mjs");
const MODULES = ["PRE", "WAH", "DST", "NS", "AMP", "NR", "CAB", "EQ", "MOD", "DLY", "RVB", "VOL"];
const KINDS = ["Knob", "Switch", "Combox", "Knob"];

const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${COMMIT}/effect-wire-schema.json`);
if (!res.ok) throw new Error(`effect-wire-schema.json: HTTP ${res.status}`);
const schema = await res.json();

const num = (v) => {
  const n = Number.parseFloat(String(v));
  if (Number.isNaN(n)) throw new Error(`not a number: ${v}`);
  return n;
};

/** Menu labels: "Off/On", "Guitar,Bass", "Standard, Jumbo, …". */
function labelsOf(p) {
  const shown = p.show?.[0]?.showValue ?? p.valueRange;
  const parts = String(shown).split(/[,/]/).map((s) => s.trim()).filter(Boolean);
  const count = num(p.max) - num(p.min) + 1;
  return parts.length === count ? parts : null;
}

function knobOf(p) {
  const kind = KINDS[p.widgetType] ?? "Knob";
  const k = { kind, name: p.name, id: p.algId, default: num(p.defaultValue), min: num(p.min), max: num(p.max), step: num(p.step) || 1 };
  if (kind !== "Knob") {
    const labels = labelsOf(p);
    if (labels) k.labels = labels;
  } else {
    // "0.10Hz-10.00Hz", "20ms-1000ms": the unit Suite shows
    const unit = /([A-Za-z%]+)\s*$/.exec(String(p.valueRange))?.[1];
    if (unit) k.unit = unit;
  }
  const sync = Number.parseInt(String(p.sync), 10);
  if (sync >= 0) k.sync = sync;
  return k;
}

const modules = MODULES.map((module, moduleId) => ({
  module,
  algs: schema
    .filter((e) => e.moduleId === moduleId)
    .filter((e, i, all) => all.findIndex((x) => x.fxid === e.fxid) === i)
    .map((e, index) => ({ name: e.variant, module, code: e.fxid >>> 0, index, knobs: e.parameters.map(knobOf).sort((a, b) => a.id - b.id) })),
}));

const algs = modules.flatMap((m) => m.algs);
const catalog = {
  meta: {
    device: "GP-150",
    source: `${REPO}@${COMMIT.slice(0, 7)}`,
    counts: {
      algEntries: algs.length,
      uniqueCodes: new Set(algs.map((a) => a.code)).size,
      perModule: Object.fromEntries(modules.map((m) => [m.module, m.algs.length])),
      controls: algs.reduce((n, a) => n + a.knobs.length, 0),
    },
  },
  modules,
};

writeFileSync(
  OUT,
  `// Generated by scripts/gp150-catalog-from-gp180-re.mjs. Do not edit by hand.
// GP-150 effect catalog from ${REPO} (GPL-3.0) at ${COMMIT}: effect-wire-schema.json, the normalized form of Valeton
// Suite 2.1.0's module150_data.json (shared by the GP-150 and GP-180).
/** @type {import("./catalog.mjs").Gp150Catalog} */
export const GP150_CATALOG = ${JSON.stringify(catalog)};
`,
);
console.log(`${OUT}: ${catalog.meta.counts.uniqueCodes} models, ${catalog.meta.counts.algEntries} entries, ${catalog.meta.counts.controls} controls`, catalog.meta.counts.perModule);
